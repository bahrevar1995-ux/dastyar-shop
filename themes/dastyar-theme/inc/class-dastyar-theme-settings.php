	/** همه تنظیمات (مرج‌شده با پیش‌فرض‌ها) */
	public static function all() {
		$saved = get_option( self::OPTION, array() );
		if ( ! is_array( $saved ) ) {
			$saved = array();
		}
		return array_merge( self::defaults(), $saved );
	}

	/** گرفتن یک کلید */
	public static function get( $key, $fallback = null ) {
		$all = self::all();
		return array_key_exists( $key, $all ) ? $all[ $key ] : $fallback;
	}

	/** بله/خیر شدن یک کلید */
	public static function yes( $key ) {
		return 'no' !== (string) self::get( $key, 'yes' );
	}

	/**
	 * v2.1.0 — نمایش هیروی برگه داخلی برای یک نوع برگه.
	 * کلید اصلی page_hero_on خاموش باشد ← هیچ هیرویی در هیچ برگه‌ای نیست؛
	 * در غیر این صورت هر برگه سوییچ مستقل ph_{id} خودش را دارد.
	 */
	public static function page_hero_on( $id = '' ) {
		if ( ! self::yes( 'page_hero_on' ) ) {
			return false;
		}
		return '' === $id ? true : self::yes( 'ph_' . $id );
	}

